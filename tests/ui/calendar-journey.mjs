import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {captureJourney} from './viewport-evidence.mjs';
export async function calendarJourney({page,api,base,out}) {
  const ci=await api('/services',{name:'Calendar Denver payroll',description:'Payroll workflow',businessImpact:'Payroll blocked',source:'Reviewed service register',observedAt:new Date().toISOString(),visibility:'operators'});
  const body={title:'Calendar payroll upgrade',risk:'Bounded upgrade',impact:'Payroll may be interrupted',services:[ci.id],cohorts:['Denver'],canaryCohorts:['Denver'],window:{start:'2030-12-27T01:00:00Z',end:'2030-12-27T02:00:00Z'},implementation:{release:'reviewed-2031'},compensation:{release:'reviewed-2030'}};
  await api('/changes',body);
  await page.goto(base+'/app#/changes');
  const region=page.getByRole('region',{name:'Change calendar',exact:true}),range=region.locator(':scope > form');
  await range.getByLabel('Calendar from').fill('2030-12-01T00:00');
  await range.getByLabel('Calendar until').fill('2031-02-01T00:00');
  await range.getByLabel('Calendar display timezone').fill('America/Denver');
  const ranged=page.waitForResponse(r=>r.url().includes('/change-calendar?')&&r.url().includes('America%2FDenver'));
  await range.getByRole('button',{name:'Show calendar',exact:true}).click();assert.equal((await ranged).status(),200);
  await region.getByRole('link',{name:body.title,exact:true}).waitFor();
  const form=region.locator('details').filter({has:page.getByText('Add calendar window',{exact:true})});
  await form.locator(':scope > summary').click();
  await form.getByLabel('Window name').fill('Calendar year-end freeze');
  await form.getByLabel('Window kind').selectOption('freeze');
  await form.getByLabel('Window starts').fill('2030-12-24T00:00');
  await form.getByLabel('Window ends').fill('2031-01-02T00:00');
  await form.getByLabel('All configuration items').uncheck();
  await form.getByLabel(ci.data.name).check();
  await captureJourney(page,{path:out+'/CHANGE-004-window-editor.png',fullPage:true});
  const saved=page.waitForResponse(r=>r.url().endsWith('/change-windows')&&r.request().method()==='POST');
  await form.getByRole('button',{name:'Save calendar window',exact:true}).click();assert.equal((await saved).status(),201);
  await region.getByRole('heading',{name:'Calendar year-end freeze',exact:true}).waitFor();
  await region.getByText('Overlaps an active freeze.',{exact:true}).waitFor();
  const refused=await page.evaluate(async body=>{
    const session=await(await fetch('/api/v1/session')).json();const r=await fetch('/api/v1/changes',{method:'POST',headers:{'Content-Type':'application/json','X-Linen-CSRF':session.csrfToken},body:JSON.stringify(body)});return {status:r.status,body:await r.json()};
  },{...body,title:'Refused calendar upgrade'});
  assert.equal(refused.status,409,'CHANGE-004 native API scheduling into freeze is refused');assert.equal(refused.body.error.code,'calendar_frozen');
  await form.locator(':scope > summary').click();
  const downloadEvent=page.waitForEvent('download');await region.getByRole('link',{name:'Download calendar (ICS)',exact:true}).click();
  const download=await downloadEvent;assert.equal(download.suggestedFilename(),'linen-change-calendar.ics');
  const contents=await readFile(await download.path(),'utf8');assert.ok(contents.includes('BEGIN:VCALENDAR'));assert.ok(contents.includes('Calendar year-end freeze'),'CHANGE-004 native calendar link downloads scoped real ICS');
  const url=await region.getByRole('link',{name:'Download calendar (ICS)',exact:true}).getAttribute('href');
  assert.equal((await fetch(base+url)).status,401,'CHANGE-004 calendar feed requires a current session');
  await captureJourney(page,{path:out+'/CHANGE-004-calendar.png',fullPage:true});
  await page.getByText('Add change',{exact:true}).click();
  await page.getByLabel('Emergency change').waitFor();
  await captureJourney(page,{path:out+'/CHANGE-004-emergency-draft.png',fullPage:true});
  await page.getByText('Add change',{exact:true}).click();
  const edit=region.locator('details').filter({has:page.getByText('Edit Calendar year-end freeze',{exact:true})});
  await edit.locator(':scope > summary').click();await edit.getByLabel('Active window').uncheck();
  const amended=page.waitForResponse(r=>/\/change-windows\/[\w-]+$/.test(r.url())&&r.request().method()==='POST');
  await edit.getByRole('button',{name:'Save calendar window',exact:true}).click();assert.equal((await amended).status(),200);
  await region.getByText('freeze · inactive',{exact:true}).waitFor();
  await captureJourney(page,{path:out+'/CHANGE-004-inactive-window.png',fullPage:true});
  await region.getByRole('link',{name:body.title,exact:true}).click();
  const amend=page.locator('details').filter({has:page.getByText('Advanced: amend the implementation',{exact:true})});
  await amend.locator(':scope > summary').click();
  await amend.getByLabel('Emergency change').waitFor();
  await captureJourney(page,{path:out+'/CHANGE-004-emergency-amend.png',fullPage:true});
}

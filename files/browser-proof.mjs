import assert from 'node:assert/strict';
import { writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const root=process.cwd();
const { chromium }=await import(pathToFileURL(root+'/node_modules/playwright/index.mjs'));
const { apiFor, finishFirstRun, signIn }=await import(pathToFileURL(root+'/tests/ui/connected-helpers.mjs'));
const { captureJourney }=await import(pathToFileURL(root+'/tests/ui/viewport-evidence.mjs'));
const base=process.env.LINEN_TEST_URL, out=process.env.LINEN_PROOF_PACKET;
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-mock-keychain','--password-store=basic']});
const context=await browser.newContext({timezoneId:'UTC',viewport:{width:1440,height:1000}});
const page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(String(error)));
page.setDefaultTimeout(15000);
try {
  await mkdir(out,{recursive:true});
  await page.goto(base+'/app');
  await page.getByLabel('Your name').fill('Synthetic Linen Owner');
  await page.getByLabel('Workspace name').fill('Knowledge expiry proof');
  await page.getByLabel('Work email').fill(['synthetic-linen-owner','example.test'].join(String.fromCharCode(64)));
  await page.getByLabel('Password',{exact:true}).fill('synthetic-linen-23 password');
  await page.getByRole('button',{name:'Create workspace'}).click();
  await page.getByRole('heading',{name:'Requests',exact:true}).waitFor();
  await finishFirstRun(page,base);
  const ownerApi=apiFor(page);
  const employeeEmail=['synthetic-linen-employee','example.test'].join(String.fromCharCode(64));
  await ownerApi('/members',{email:employeeEmail,name:'Synthetic Linen Employee',password:'synthetic-linen-24 password',roles:['employee']});
  const expiry=Date.now()+20_000;
  const article=await ownerApi('/knowledge',{title:'VPN reviewed guidance',body:'Reviewed network guidance',scope:'employees',expiresAt:new Date(expiry).toISOString(),review:true});
  const current=await ownerApi('/knowledge',{title:'VPN current guidance',body:'Reviewed guidance that remains available',scope:'employees',expiresAt:new Date(expiry+60_000).toISOString(),review:true});
  const employeeContext=await browser.newContext({timezoneId:'UTC',viewport:{width:1440,height:1000}});
  const employeePage=await employeeContext.newPage();
  employeePage.on('pageerror',error=>errors.push(String(error)));
  await signIn(employeePage,base,employeeEmail,'synthetic-linen-24 password');
  const employeeApi=apiFor(employeePage);
  const before=await employeeApi('/knowledge?q=VPN'), beforeAt=Date.now();
  assert.ok(beforeAt<expiry);
  assert.deepEqual(before.items.map(item=>item.id).sort(),[article.id,current.id].sort());
  await employeePage.goto(base+'/app#/knowledge?q=VPN');
  await employeePage.getByRole('heading',{name:'VPN reviewed guidance',exact:true}).waitFor();
  await employeePage.getByRole('heading',{name:'VPN current guidance',exact:true}).waitFor();
  await captureJourney(employeePage,{path:out+'/knowledge-before.png',fullPage:true});
  await new Promise(resolve=>setTimeout(resolve,Math.max(0,expiry-Date.now())+100));
  const afterAt=Date.now();
  assert.ok(afterAt>expiry);
  const after=await employeeApi('/knowledge?q=VPN');
  assert.deepEqual(after.items.map(item=>item.id),[current.id]);
  await employeePage.reload();
  await employeePage.getByRole('heading',{name:'VPN current guidance',exact:true}).waitFor();
  assert.equal(await employeePage.getByRole('heading',{name:'VPN reviewed guidance',exact:true}).count(),0);
  await captureJourney(employeePage,{path:out+'/knowledge-after.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await writeFile(out+'/browser-receipt.json',JSON.stringify({head:process.env.LINEN_PROOF_HEAD,command:'node tests/ui/run.mjs ../browser-proof.mjs',assertionWidth:1440,captureWidths:[1440,390],beforeAt,expiresAt:expiry,afterAt,beforeIds:before.items.map(item=>item.id),afterIds:after.items.map(item=>item.id),pageErrors:errors,result:'passed'},null,2)+'\n');
  console.log('PASS KB-001 native employee Knowledge before and after real expiry; captured 1440 and 390');
  await employeeContext.close();
} finally { await browser.close(); }
